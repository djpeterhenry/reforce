#!/usr/bin/env python3
"""Geometry of the Phase 5C audio probes, shared by the config/timeline generator and the decoder.

    python3 -I tools/parity/audio_layout.py --write     (re)write the probe configs + timelines run7..run16, run23

Everything is in G-Force frame units (x, y in [-1, 1], +y up, Aspc=0). Probe resolution: 1980x1260 (G-Force's
TakeScreenshot() size in the windowed runs), so 1 px = 2/1980 in x and 2/1260 in y.

STRIP CHART ("zz reforce strip" FlowField + WaveShape; split screen)
  * Top region y > Y_SPLIT: the FlowField scrolls left by exactly 1 px per frame (srcX = x + 2/1980,
    srcY = y). Every frame the WaveShape draws one dot per signal at x = STRIP_X (right edge, px ~1969.5),
    so column c holds the dot drawn (1969.5 - c) frames ago. G-Force decays 1/255 per frame (probe #6), so a
    dot drawn at Pen 1 (255) is visible for ~250 frames (~4.2 s at 60 fps, ~4.5 s at G-Force's effective
    55.6 fps): one screenshot covers ~4 s; timelines take a shot every 3 s (overlap for stitching). The
    pixel value also encodes the age: age = 255 - value.
  * Each signal has a band. Value v maps to y = yu0 + h * clamp((v - lo) / (hi - lo)) (affine, clamped);
    rails (fixed dots) at u = -0.1 and u = 1.1 draw two horizontal lines that make the scale readable and
    let the decoder verify the map. Band 0 is the time base: u = wrap(t / 8) (8 s sawtooth of `t`).
  * Bottom region y <= Y_SPLIT: srcX = srcY = 9 (void, cleared every frame) holds a snapshot of the whole
    fft(s) curve (top) and mag(s) curve (bottom) as NUM_FFT_BINS dots, x = SNAP_X0 + SNAP_XW * s.
SPECTRUM ("zz reforce spectrum" WaveShape on "zz reforce void"): the same two snapshot curves, full screen.
"""
import json
import os
import sys

REPO = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", ".."))
WIDTH, HEIGHT = 1980, 1260

# ---- strip chart ---------------------------------------------------------------------------------------------
Y_SPLIT = -0.25
STRIP_X = 0.99
TIME_PERIOD = 8.0
# key, expression, lo, hi
SIGNALS = [
    ("time", "wrap(t / %g)" % TIME_PERIOD, 0.0, 1.0),
    ("LEVEL", "LEVEL", 0.0, 1.0),
    ("BASS", "BASS", 0.0, 2.0),
    ("ENERGY", "ENERGY", 0.0, 2.0),
    ("fft.05", "fft(.05)", 0.0, 2.0),
    ("fft.2", "fft(.2)", 0.0, 2.0),
    ("fft.5", "fft(.5)", 0.0, 2.0),
    ("fft.8", "fft(.8)", 0.0, 2.0),
    ("mag.5", "mag(.5)", -1.0, 1.0),
]
RAIL_LO, RAIL_HI = -0.1, 1.1
BAND_H = (1.0 - Y_SPLIT) / len(SIGNALS)
USE_H = 0.7 * BAND_H          # height of u in [0, 1]
USE_OFF = 0.15 * BAND_H       # band bottom -> u = 0


def band(k):
    """-> dict(key, expr, lo, hi, y0 (u=0), h, ylo/yhi (band edges), rail_lo, rail_hi) for strip band k."""
    key, expr, lo, hi = SIGNALS[k]
    top = 1.0 - k * BAND_H
    bottom = top - BAND_H
    y0 = bottom + USE_OFF
    return {"key": key, "expr": expr, "lo": lo, "hi": hi, "y0": y0, "h": USE_H, "ylo": bottom, "yhi": top,
            "rail_lo": y0 + RAIL_LO * USE_H, "rail_hi": y0 + RAIL_HI * USE_H}


# ---- snapshot curves -------------------------------------------------------------------------------------------
SNAP_X0, SNAP_XW = -0.98, 1.96
# name -> {curve: (y0, h, lo, hi)} ; u = clamp((v - lo)/(hi - lo)), y = y0 + h * u
SNAPSHOTS = {
    "strip": {"fft": (-0.58, 0.30, 0.0, 2.0), "mag": (-0.97, 0.34, -1.0, 1.0)},
    "spectrum": {"fft": (0.05, 0.90, 0.0, 3.0), "mag": (-0.95, 0.90, -1.0, 1.0)},
}
SNAP_EXPR = {"fft": "fft(s)", "mag": "mag(s)"}


def _fmt(v):
    s = ("%.6f" % v).rstrip("0").rstrip(".")
    return s if s not in ("-0", "") else "0"


def _u(expr, lo, hi):
    """clamp((v - lo) / (hi - lo)), written without '- -' (no unary minus after a binary operator)."""
    num = expr if lo == 0 else "(%s %s %s)" % (expr, "+" if lo < 0 else "-", _fmt(abs(lo)))
    return "clamp(%s / %s)" % (num, _fmt(hi - lo))


def strip_waveshape():
    lines = ["// reforce probe (Phase 5C strip chart; generated by tools/parity/audio_layout.py --write, do not edit).",
             "// Use with FlowField 'zz reforce strip' (top region scrolls left 1 px/frame at 1980 px width) and",
             "// ColorMap 'zz reforce gray' + MapFunction \"i\". Paths 0-%d: one dot per signal at x = %g, three"
             % (len(SIGNALS) - 1, STRIP_X),
             "// groups of s steps: s < .25 lower rail (u = -0.1), s > .75 upper rail (u = 1.1), else the signal,",
             "// y = y0 + h * clamp((v - lo) / (hi - lo)). Bands (top to bottom):"]
    for k in range(len(SIGNALS)):
        b = band(k)
        lines.append("//   path %d  %-7s %-14s lo %-4g hi %-4g y0 %.5f h %.5f" % (k, b["key"], b["expr"], b["lo"], b["hi"],
                                                                                  b["y0"], b["h"]))
    snap = SNAPSHOTS["strip"]
    lines.append("// Paths %d/%d: snapshot of fft(s) / mag(s) in the void region y <= %g, x = %g + %g * s."
                 % (len(SIGNALS), len(SIGNALS) + 1, Y_SPLIT, SNAP_X0, SNAP_XW))
    lines += ["Stps=\"NUM_FFT_BINS\"", "ConB=0", "LWdt=1", "Aspc=0"]
    for k in range(len(SIGNALS)):
        b = band(k)
        lines.append('X%d="%s"' % (k, _fmt(STRIP_X)))
        lines.append('Y%d="%s + %s * (%s * (s < .25) + %s * (s > .75) + (s > .25) * (s < .75) * %s)"'
                     % (k, _fmt(b["y0"]), _fmt(b["h"]), _fmt(RAIL_LO), _fmt(RAIL_HI), _u(b["expr"], b["lo"], b["hi"])))
    lines += _snap_paths(len(SIGNALS), snap)
    lines.append("Vers=270")
    return "\n".join(lines) + "\n"


def _snap_paths(first, snap):
    out = []
    for i, curve in enumerate(("fft", "mag")):
        y0, h, lo, hi = snap[curve]
        out.append('X%d="%s + %s * s"' % (first + i, _fmt(SNAP_X0), _fmt(SNAP_XW)))
        out.append('Y%d="%s + %s * %s"' % (first + i, _fmt(y0), _fmt(h), _u(SNAP_EXPR[curve], lo, hi)))
    return out


def spectrum_waveshape():
    snap = SNAPSHOTS["spectrum"]
    lines = ["// reforce probe (Phase 5C snapshot; generated by tools/parity/audio_layout.py --write, do not edit).",
             "// Use with FlowField 'zz reforce void'. NUM_FFT_BINS dots at x = %g + %g * s:" % (SNAP_X0, SNAP_XW)]
    for curve in ("fft", "mag"):
        y0, h, lo, hi = snap[curve]
        lines.append("//   %s: y = %g + %g * %s" % (curve, y0, h, _u(SNAP_EXPR[curve], lo, hi)))
    lines += ["Stps=\"NUM_FFT_BINS\"", "ConB=0", "LWdt=1", "Aspc=0"] + _snap_paths(0, snap) + ["Vers=270"]
    return "\n".join(lines) + "\n"


def strip_flowfield():
    return "\n".join([
        "// reforce probe (Phase 5C strip chart; generated by tools/parity/audio_layout.py --write, do not edit).",
        "// Top region (y > %g): source = one pixel to the right, so the image scrolls LEFT by exactly 1 px per" % Y_SPLIT,
        "// frame at the probe width of %d px (1 px = 2/%d frame units). Bottom region: void (source far outside" % (WIDTH, WIDTH),
        "// the frame -> cleared every frame) for the snapshot curves.",
        "Aspc=0",
        'srcX="(y > %s) * (x + 2/%d) + (y <= %s) * 9"' % (_fmt(Y_SPLIT), WIDTH, _fmt(Y_SPLIT)),
        'srcY="(y > %s) * y + (y <= %s) * 9"' % (_fmt(Y_SPLIT), _fmt(Y_SPLIT)),
        "Vers=100"]) + "\n"


# ---- timelines ------------------------------------------------------------------------------------------------
AUDIO_DELAY = 2.0     # run.sh starts the player this long after the Shift+R,5 keypress (= timeline 0:00)
STRIP_SHOT_EVERY = 3.0
# run -> (wav stem, kind, extra)
RUNS = {
    "run7": ("tone_steps", "strip"),
    "run8": ("sweep", "strip"),
    "run9": ("noise_bands", "strip"),
    "run10": ("kick120", "strip"),
    "run11": ("attack_release", "strip"),
    "run12": ("silence", "strip"),
    "run13": ("sweep", "spectrum"),
    "run14": ("noise_bands", "spectrum"),
    # follow-up (2026-11-11 evening): tones at six frequencies, a 20 s tone, a falling sweep
    "run15": ("tone_freqs", "strip"),
    "run16": ("tone_freqs", "spectrum"),
    "run23": ("tone_pairs", "spectrum"),
}


def wav_meta(stem):
    with open(os.path.join(REPO, "probes", "audio", stem + ".json")) as f:
        return json.load(f)


def _ts(t):
    m, s = divmod(t, 60.0)
    return "%d:%s" % (int(m), ("%05.2f" % s).rstrip("0").rstrip("."))


def shot_times(run):
    stem, kind = RUNS[run]
    dur = wav_meta(stem)["duration"]
    D = AUDIO_DELAY
    if kind == "strip":
        # First shot 2 s after the audio starts: its ~4 s of history reach back before the sync click (0.525 s).
        ts, t = [], D + 2.0
        while True:
            ts.append(round(t, 2))
            if t >= D + dur + 0.5:
                break
            t += STRIP_SHOT_EVERY
        return ts
    # spectrum: one shot every 0.5 s through the content (+ one before the content as a baseline)
    meta = wav_meta(stem)
    ts = [round(D + meta["content_start"] - 0.5, 2)]
    t = D + meta["content_start"] + 0.25
    while t < D + dur - 2.0:
        ts.append(round(t, 2))
        t += 0.5
    return ts


def timeline(run):
    stem, kind = RUNS[run]
    meta = wav_meta(stem)
    shots = shot_times(run)
    seconds = int(shots[-1] + 6)
    ff, ws = ("zz reforce strip", "zz reforce strip") if kind == "strip" else ("zz reforce void", "zz reforce spectrum")
    out = ["# reforce black-box probe %s (G-Force script, Python 2.7): Phase 5C audio, %s probe." % (run, kind),
           "# Generated by tools/parity/audio_layout.py --write (do not edit).",
           "# reforce-audio: %s.wav delay=%g seconds=%d" % (stem, AUDIO_DELAY, seconds),
           "# run.sh plays probes/audio/%s.wav (%.2f s, sync click at %.3f s) to the 'reforce probe' device %g s after"
           % (stem, meta["duration"], meta["sync"]["t"] + meta["sync"]["duration"] / 2, AUDIO_DELAY),
           "# the Shift+R,5 keypress (= 0:00 here); G-Force reads it via Audio.InputSource = \"reforce probe\".",
           "def ws( name, morph = 0 ):  vis.StartConfig( 'WaveShape', name, morph )",
           "def cm( name, morph = 0 ):  vis.StartConfig( 'ColorMap', name, morph )",
           "def ff( name, morph = 0 ):  vis.SetFlowField( name, '', morph, 0, True )",
           "def shot( label ):",
           "    print \"reforce-probe shot: %s\" % label",
           "    vis.TakeScreenshot()",
           "",
           "@_time( '0:00' )",
           "def a000():",
           "    vis.SetSlideshowEnabled( '*', False ); vis.KillRunningParticles( 0 ); vis.KillRunningSprites( 0 )",
           "    vis.SetConsoleVisible( False )",
           "    cm( 'zz reforce gray' ); ff( '%s' ); ws( '%s' )" % (ff, ws)]
    for i, t in enumerate(shots):
        fn = "s%03d" % (i + 1)
        out += ["@_time( '%s' )" % _ts(t),
                "def %s(): shot( '%02d-%s-t%05.2f' )%s# %04d" % (fn, i + 1, kind, t, " " * 8, i + 1)]
    out += ["@_time( '%s' )" % _ts(shots[-1] + 1.0), "def done(): print \"reforce-probe: done\""]
    return "\n".join(out) + "\n"


def parse_header(path):
    """'# reforce-audio: file.wav delay=D seconds=S' -> (stem, delay, seconds) or None."""
    for line in open(path, encoding="utf-8"):
        if line.startswith("# reforce-audio:"):
            parts = line.split(":", 1)[1].split()
            kv = dict(p.split("=", 1) for p in parts[1:])
            return os.path.splitext(parts[0])[0], float(kv.get("delay", AUDIO_DELAY)), float(kv.get("seconds", 60))
    return None


def write_all():
    files = {
        os.path.join("probes", "FlowField", "zz reforce strip.txt"): strip_flowfield(),
        os.path.join("probes", "WaveShape", "zz reforce strip.txt"): strip_waveshape(),
        os.path.join("probes", "WaveShape", "zz reforce spectrum.txt"): spectrum_waveshape(),
    }
    for run in RUNS:
        files[os.path.join("probes", "timelines", run + ".py")] = timeline(run)
    for rel, text in files.items():
        with open(os.path.join(REPO, rel), "w") as f:
            f.write(text)
        print("wrote", rel)


if __name__ == "__main__":
    if "--write" in sys.argv[1:]:
        write_all()
    else:
        print(__doc__)
