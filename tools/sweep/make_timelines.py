#!/usr/bin/env python3
"""Phase 5B.4 corpus sweep: generate the G-Force timelines probes/timelines/sweep_*.py.

    python3 -I tools/sweep/make_timelines.py [--reforce PATH] [--scenes DIR] [--ff-parts 4] [--check]

Inventories every FlowField and ColorMap under scenes/Packages, classifies each with
`reforce --describe-config` (see sweeplib.py for the classes), writes de-randomized copies of configs whose
load-time (A var) rnd() can be fixed (build/sweep/derived/, local only: SoundSpectrum content), and writes
the timelines plus build/sweep/manifest.json. --check only prints the inventory and the class counts.

Timing (all G-Force times are scripted wall-clock times relative to the Shift+R,5 keypress = 0:00):

FlowField slot (FF_SLOT = 2.5 s per field, 4 timelines of 88 fields = 3.7 min each, 14.7 min in total):
  +0.0  ff('zz reforce void')   clears the screen within one frame (every pixel samples off-screen).
  +0.1  ff(<field>)             cut (morph 0), SetFlowField(..., inSwitchOnTime=True): G-Force finishes the
                                threaded field build first, so the field starts at this time + its build stall.
  +2.4  shot
  WaveShape 'zz reforce sweep grid' redraws a fixed pattern every frame at Pen .4 (intensity 102). Decay is
  linear, 1/255 per frame (docs/probe-results.md #6), so every pixel is at most 102 levels and anything drawn
  more than 102 frames ago has decayed to exactly 0: after 102 frames under the field the image is EXACTLY
  its steady state, independent of the screenshot time, frame rate jitter and the previous field.
  102 frames take 1.70 s at 60 fps and 1.84 s at the ~55.6 fps G-Force really runs here (PLAN 5B.3); the
  shot at +2.3 s after the switch leaves 0.46 s (26 frames) for G-Force's build stall and the screenshot
  landing +-2 frames early. If a build stalls longer, only the faintest trail ages (levels < ~26 of 102) are
  missing, because the void cleared the previous field: the comparison degrades gracefully.
  A shorter slot would need a lower Pen (less signal); 2.5 s x 352 = 14.7 min meets the 15 min budget.

ColorMap slot (CM_SLOT = 0.8 s per map, 1 timeline, 250 maps incl. the gray reference = 3.3 min):
  +0.0  cm(<map>)  cut;  +0.7 shot. The 'void' field clears every frame and WaveShape 'zz reforce sweep ramp'
  draws 256 dots with Pen = k/255 in three rows, so a shot is one frame and the dot centers ARE the palette.
  0.7 s covers a palette (re)compute (CCal ~0.09 s) and a PNG strip load. Slot 1 is our 'zz reforce gray'
  (palette = identity) to check the reading geometry on both sides.

Config names: G-Force's script API addresses configs by entry name = file basename without extension
(our probes in 'zz reforce probes/' have always been addressed so). The corpus has no duplicate basenames
per type (checked here; duplicates would be skipped and reported). -icon.png thumbnails are not ColorMaps.
"""
import argparse
import json
import os
import shutil
import sys

sys.dont_write_bytecode = True
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import sweeplib as S  # noqa: E402

FF_SLOT, FF_CLEAR_TO_SWITCH, FF_SHOT = 2.5, 0.1, 2.4
CM_SLOT, CM_SHOT = 0.8, 0.7
START = 1.0   # first slot (0:00 = setup)
MARGIN = 3.0  # run.sh waits PROBE_SECONDS = last event + MARGIN

HEAD = """# reforce black-box probe {tl} (G-Force script, Python 2.7): Phase 5B.4 {kind} corpus sweep, part {part} of {parts}.
# Generated by tools/sweep/make_timelines.py (do not edit; timing rationale in its docstring).
# reforce-sweep: kind={kind} part={part}/{parts} slots={n} slot={slot} seconds={secs}
# Run: tools/sweep/run_gforce_sweeps.sh (installs the 'zz sweep' derived configs, sets PROBE_SECONDS={secs}).
# Each slot's comment: class and source config (relative to scenes/Packages or build/sweep/derived/Packages).
def ws( name, morph = 0 ):  vis.StartConfig( 'WaveShape', name, morph )
def cm( name, morph = 0 ):  vis.StartConfig( 'ColorMap', name, morph )
def ff( name, union = '', morph = 0 ):  vis.SetFlowField( name, union, morph, 0, True )
def shot( label ):
    print "reforce-probe shot: %s" % label
    vis.TakeScreenshot()
def setup( c, f, w ):
    vis.SetSlideshowEnabled( '*', False ); vis.KillRunningParticles( 0 ); vis.KillRunningSprites( 0 )
    vis.SetConsoleVisible( False )
    cm( c ); ff( f ); ws( w )

@_time( '0:00' )
def a000(): setup( {setup} )
"""


def q(name):
    return repr(str(name))  # Python 2 string literal (ASCII names; repr picks quotes around apostrophes)


def plan(reforce, scenes):
    """-> {kind: [entry]} with entry = dict(name, src, cls, run_name, run_path, describe flags)."""
    out = {}
    if os.path.isdir(S.DERIVED):
        shutil.rmtree(S.DERIVED)
    for kind in ("FlowField", "ColorMap"):
        entries = S.corpus(kind, scenes)
        dups = S.duplicates(entries)
        txt = [p for _, p in entries if p.lower().endswith(".txt")]
        desc = S.describe(reforce, txt)
        derived = {}
        for name, path in entries:
            d = desc.get(path)
            if d is not None and S.load_random(d):
                dp = S.write_derived(kind, name, path)
                if dp:
                    derived[path] = dp
        ddesc = S.describe(reforce, list(derived.values())) if derived else {}
        rows = []
        for name, path in entries:
            d = desc.get(path)
            dp = derived.get(path)
            dd = ddesc.get(dp) if dp else None
            if dd is not None and (dd["errors"] != d["errors"]):
                dp, dd = None, None  # the rewrite broke something: run the original
            cls = S.classify(kind, d, dd)
            row = {"name": name, "src": os.path.relpath(path, S.REPO), "cls": cls,
                   "run_name": S.DERIVED_PREFIX + name if dp else name,
                   "run_path": os.path.relpath(dp or path, S.REPO),
                   "builtins": (dd or d or {}).get("builtins", []),
                   "errors": (d or {}).get("errors", 0)}
            if name.lower() in dups:
                row["cls"] = "skip-duplicate"
            rows.append(row)
        out[kind] = rows
    return out


def write_ff(rows, parts):
    rows = [r for r in rows if not r["cls"].startswith("skip")]
    per = -(-len(rows) // parts)
    names = []
    for p in range(parts):
        chunk = rows[p * per:(p + 1) * per]
        if not chunk:
            continue
        tl = "sweep_ff_%02d" % (p + 1)
        last = START + (len(chunk) - 1) * FF_SLOT + FF_SHOT
        secs = int(last + MARGIN + 0.999)
        body = HEAD.format(tl=tl, kind="FlowField", part=p + 1, parts=parts, n=len(chunk), slot=FF_SLOT, secs=secs,
                           setup=", ".join(q(n) for n in ("zz reforce gray", "zz reforce void", "zz reforce sweep grid")))
        for i, r in enumerate(chunk, 1):
            t0 = START + (i - 1) * FF_SLOT
            body += "@_time( '%s' )\ndef c%03d(): ff( 'zz reforce void' )\n" % (S.fmt_time(t0), i)
            body += "@_time( '%s' )\ndef x%03d(): ff( %s )  # %s %s\n" % (
                S.fmt_time(t0 + FF_CLEAR_TO_SWITCH), i, q(r["run_name"]), r["cls"], r["run_path"])
            body += "@_time( '%s' )\ndef s%03d(): shot( '%03d' )\n" % (S.fmt_time(t0 + FF_SHOT), i, i)
        body += "@_time( '%s' )\ndef z999(): print \"reforce-probe: done\"\n" % S.fmt_time(last + 1)
        open(os.path.join(S.TIMELINE_DIR, tl + ".py"), "w").write(body)
        names.append((tl, len(chunk), secs))
    return names


def write_cm(rows):
    rows = [r for r in rows if not r["cls"].startswith("skip")]
    ref = {"name": "zz reforce gray", "cls": "ref", "run_name": "zz reforce gray",
           "run_path": os.path.relpath(S.probe_path("gray"), S.REPO)}
    rows = [ref] + rows
    tl = "sweep_cm_01"
    last = START + (len(rows) - 1) * CM_SLOT + CM_SHOT
    secs = int(last + MARGIN + 0.999)
    body = HEAD.format(tl=tl, kind="ColorMap", part=1, parts=1, n=len(rows), slot=CM_SLOT, secs=secs,
                       setup=", ".join(q(n) for n in ("zz reforce gray", "zz reforce void", "zz reforce sweep ramp")))
    for i, r in enumerate(rows, 1):
        t0 = START + (i - 1) * CM_SLOT
        body += "@_time( '%s' )\ndef x%03d(): cm( %s )  # %s %s\n" % (S.fmt_time(t0), i, q(r["run_name"]), r["cls"],
                                                                     r["run_path"])
        body += "@_time( '%s' )\ndef s%03d(): shot( '%03d' )\n" % (S.fmt_time(t0 + CM_SHOT), i, i)
    body += "@_time( '%s' )\ndef z999(): print \"reforce-probe: done\"\n" % S.fmt_time(last + 1)
    open(os.path.join(S.TIMELINE_DIR, tl + ".py"), "w").write(body)
    return [(tl, len(rows), secs)]


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--reforce", default=S.DEFAULT_REFORCE)
    ap.add_argument("--scenes", default=S.SCENES)
    ap.add_argument("--ff-parts", type=int, default=4)
    ap.add_argument("--check", action="store_true", help="print inventory and class counts only")
    a = ap.parse_args()
    if not os.path.isdir(os.path.join(a.scenes, "Packages")):
        sys.exit("no scenes at %s (scripts/sync-scenes.sh)" % a.scenes)
    if not os.access(a.reforce, os.X_OK):
        sys.exit("no reforce binary at %s (cmake --build build)" % a.reforce)
    for k in S.PROBE:
        if not os.path.isfile(S.probe_path(k)):
            sys.exit("missing probe config %s" % S.probe_path(k))
    pl = plan(a.reforce, a.scenes)
    for kind, rows in pl.items():
        counts = {}
        for r in rows:
            counts[r["cls"]] = counts.get(r["cls"], 0) + 1
        print("%-9s %3d configs: %s" % (kind, len(rows), ", ".join("%s %d" % kv for kv in sorted(counts.items()))))
    if a.check:
        return
    for old in S.sweep_timelines():
        os.remove(os.path.join(S.TIMELINE_DIR, old + ".py"))
    made = write_ff(pl["FlowField"], a.ff_parts) + write_cm(pl["ColorMap"])
    os.makedirs(S.WORK, exist_ok=True)
    json.dump({"timelines": [{"name": n, "slots": c, "seconds": s} for n, c, s in made], "configs": pl},
              open(os.path.join(S.WORK, "manifest.json"), "w"), indent=1)
    total = 0
    for n, c, s in made:
        total += s
        print("wrote probes/timelines/%s.py: %d slots, PROBE_SECONDS=%d" % (n, c, s))
    print("G-Force time: %.1f min of timelines (+ ~20 s launch/restore per run); derived configs in %s"
          % (total / 60.0, os.path.relpath(S.DERIVED, S.REPO)))


if __name__ == "__main__":
    main()
